// Bundles the extension into out/extension.js and writes the TextMate grammars: syntaxes/lyth.tmLanguage.json
// from the docs site's grammar (website/src/lyth-grammar.mjs), so the editor and the docs color Lyth alike,
// and the Markdown injection for ```lyth blocks. `--production` minifies the bundle and writes the LICENSE file
// for the package; `--watch` rebuilds on changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const production = process.argv.includes('--production');

const { default: grammar } = await import('../../../website/src/lyth-grammar.mjs');
writeFileSync(
  'syntaxes/lyth.tmLanguage.json',
  JSON.stringify(
    {
      $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
      comment: 'Generated by scripts/build.mjs from website/src/lyth-grammar.mjs; do not edit.',
      ...grammar,
    },
    null,
    2,
  ) + '\n',
);
writeFileSync(
  'syntaxes/lyth-markdown.tmLanguage.json',
  JSON.stringify(
    {
      $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
      comment: 'Highlights ```lyth code blocks in Markdown files. Generated by scripts/build.mjs.',
      scopeName: 'markdown.lyth.codeblock',
      injectionSelector: 'L:text.html.markdown',
      patterns: [{ include: '#lyth-code-block' }],
      repository: {
        'lyth-code-block': {
          name: 'markup.fenced_code.block.markdown',
          begin: '(^|\\G)(\\s*)(`{3,}|~{3,})\\s*(?i:(lyth)((\\s+|:|,|\\{|\\?)[^`]*)?$)',
          end: '(^|\\G)(\\2|\\s{0,3})(\\3)\\s*$',
          beginCaptures: {
            3: { name: 'punctuation.definition.markdown' },
            4: { name: 'fenced_code.block.language.markdown' },
            5: { name: 'fenced_code.block.language.attributes.markdown' },
          },
          endCaptures: { 3: { name: 'punctuation.definition.markdown' } },
          patterns: [
            {
              begin: '(^|\\G)(\\s*)(.*)',
              while: '(^|\\G)(?!\\s*([`~]{3,})\\s*$)',
              contentName: 'meta.embedded.block.lyth',
              patterns: [{ include: 'source.lyth' }],
            },
          ],
        },
      },
    },
    null,
    2,
  ) + '\n',
);

const options = {
  entryPoints: ['src/extension.ts'],
  outfile: 'out/extension.js',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  external: ['vscode'],
  minify: production,
  sourcemap: !production,
  logLevel: 'info',
};

if (process.argv.includes('--watch')) {
  await (await esbuild.context(options)).watch();
} else {
  await esbuild.build(options);
}

if (production) {
  const mit = readFileSync('../../LICENSE-MIT', 'utf8');
  const apache = readFileSync('../../LICENSE-APACHE', 'utf8');
  writeFileSync('LICENSE', `Lyth for VS Code is licensed under either of the MIT license or the Apache License,\nVersion 2.0, at your option.\n\n${mit}\n\n${apache}`);
}
