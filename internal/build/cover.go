// Coverage needs two things the overlay cannot give.
//
// go test -cover runs the cover tool on every non-test file of the packages
// it instruments, and the cover tool reads those files from disk: it ignores
// -overlay (Go 1.26 and 1.27). For runs with coverage flags, lyth test
// therefore writes the generated files beside their sources for the length
// of the run (WriteForCover).
//
// The cover tool of Go 1.27 records physical positions in the generated file
// and takes only the file name from //line directives, so the profile go test
// writes names x.lyth with generated lines and columns. The cover tool of Go
// 1.26 applies the directives, which have no columns, so its profile holds
// Lyth lines without columns. For Go 1.26 the files written for a coverage
// run therefore have no directives, and the profile names x.lyth.go with
// generated positions. Either way, MapCoverProfile rewrites it to Lyth
// positions through the exact source map of the file the cover tool read.

// WriteForCover writes the generated non-test files of the session's packages
// next to their sources, where the cover tool reads them, and returns a
// function that removes them again and restores any file that lyth gen
// -in-tree had written there.
func (s *Session) WriteForCover() (restore func() error, err error) {
	type saved struct {
		path    string
		old     []byte
		existed bool
	}
	// Coverage runs of one module take turns: they write the same files.
	unlock := s.lockCover()
	var done []saved
	restore = func() error {
		defer unlock()
		var first error
		for _, f := range done {
			var err error
			if f.existed {
				err = os.WriteFile(f.path, f.old, 0o644)
			} else {
				err = os.Remove(f.path)
			}
			if err != nil && first == nil {
				first = err
			}
		}
		return first
	}
	plain := s.coverWithoutDirectives()
	for _, p := range s.Packages {
		for i, g := range p.Generated {
			if strings.HasSuffix(g.Name, "_test.go") {
				continue // test files are not instrumented; the overlay serves them
			}
			if plain && i < len(p.Lowered) {
				res, err := emit.Emit(p.Lowered[i], emit.Options{})
				if err != nil {
					restore()
					return nil, err
				}
				if s.coverGen == nil {
					s.coverGen = map[*emit.Result]*emit.Result{}
				}
				s.coverGen[g] = res
				g = res
			}
			path := filepath.Join(p.Dir.Dir, g.Name)
			if _, ok := s.coverGen[p.Generated[i]]; ok && s.Maps != nil {
				s.Maps[path] = g.Map // go's own messages name this file now
			}
			old, err := os.ReadFile(path)
			existed := err == nil
			if existed && !bytes.HasPrefix(old, []byte("// Code generated by lyth")) {
				restore()
				return nil, fmt.Errorf("refusing to overwrite %s: it was not generated by lyth", path)
			}
			if existed && bytes.Contains(firstLine(old), []byte(coverMark)) {
				existed = false // left by a coverage run that was killed: not lyth gen -in-tree's
			}
			if err := os.WriteFile(path, markCover(g.Code), 0o644); err != nil {
				restore()
				return nil, err
			}
			done = append(done, saved{path, old, existed})
		}
	}
	return restore, nil
}

// coverMark is in the first line of the files a coverage run writes, so a
// later run tells a killed run's leftovers from lyth gen -in-tree's files.
const coverMark = " for a coverage run"

// markCover marks the header of a generated file written for a coverage run:
// "// Code generated by lyth from x.lyth for a coverage run. DO NOT EDIT."
func markCover(code []byte) []byte {
	line := firstLine(code)
	i := bytes.Index(line, []byte(". DO NOT EDIT."))
	if i < 0 {
		return code
	}
	out := append([]byte(nil), code[:i]...)
	out = append(out, coverMark...)
	return append(out, code[i:]...)
}

func firstLine(b []byte) []byte {
	if i := bytes.IndexByte(b, '\n'); i >= 0 {
		return b[:i]
	}
	return b
}

// lockCover waits until no other coverage run of the module writes files
// beside its sources, and returns the function that lets the next one go.
// The lock is a file whose holder refreshes it; one that is not refreshed
// for two minutes belongs to a run that died.
func (s *Session) lockCover() func() {
	path := filepath.Join(s.Mod.Root, ".lyth", "cover.lock")
	_ = os.MkdirAll(filepath.Dir(path), 0o755)
	waited := false
	for {
		f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o644)
		if err == nil {
			fmt.Fprintf(f, "%d\n", os.Getpid())
			f.Close()
			break
		}
		if info, err := os.Stat(path); err == nil && time.Since(info.ModTime()) > 2*time.Minute || !lockHolderAlive(path) {
			os.Remove(path) // its run died
			continue
		}
		if !waited && s.cfg.Stderr != nil {
			fmt.Fprintln(s.cfg.Stderr, "lyth: waiting for another coverage run of this module")
			waited = true
		}
		time.Sleep(200 * time.Millisecond)
	}
	stop := make(chan struct{})
	go func() {
		t := time.NewTicker(30 * time.Second)
		defer t.Stop()
		for {
			select {
			case <-stop:
				return
			case now := <-t.C:
				_ = os.Chtimes(path, now, now)
			}
		}
	}()
	var once sync.Once
	return func() {
		once.Do(func() {
			close(stop)
			os.Remove(path)
		})
	}
}

// lockHolderAlive reports whether the process that wrote a lock file still
// runs (a lock that cannot be read yet is taken to be alive).
func lockHolderAlive(path string) bool {
	data, err := os.ReadFile(path)
	if err != nil {
		return true
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(data)))
	if err != nil {
		return true // being written
	}
	return processAlive(pid)
}

// coverWithoutDirectives reports whether the files of a coverage run must
// have no //line directives: the cover tool before Go 1.27 applies them, and
// their positions have no columns.
func (s *Session) coverWithoutDirectives() bool {
	if s.goEnv == nil {
		return false
	}
	_, minor := s.goEnv.Version()
	return minor != 0 && minor < 27
}

// MapCoverProfile rewrites a coverage profile that go test wrote for this
// session's packages so that its blocks are ranges of .lyth files. Lyth files
// are named by absolute path: tools resolve an import-path name with go list,
// which finds no package in a directory of Lyth files. Blocks of Go files
// pass through unchanged.
func (s *Session) MapCoverProfile(file string) error {
	profiles, err := cover.ParseProfiles(file)
	if err != nil {
		return err
	}
	if len(profiles) == 0 {
		return nil
	}
	type genFile struct {
		path string // the Lyth source
		g    *emit.Result
	}
	gens := map[string]genFile{} // "import/path/x.lyth" -> generated file
	for _, p := range s.Packages {
		for _, g := range p.Generated {
			if cg := s.coverGen[g]; cg != nil {
				g = cg // the file the cover tool read
			}
			if g.Map != nil && g.Map.Src != nil {
				gens[p.Dir.ImportPath+"/"+g.Map.Src.Base()] = genFile{g.Map.Src.Path, g}
			}
		}
	}
	// A function is named x.lyth.go when no directive precedes it, x.lyth
	// otherwise; both are blocks of the same generated file.
	var names []string
	blocks := map[string][]cover.ProfileBlock{}
	for _, prof := range profiles {
		name := prof.FileName
		if gf, ok := gens[strings.TrimSuffix(name, ".go")]; ok {
			name = gf.path
		}
		if _, ok := blocks[name]; !ok {
			names = append(names, name)
		}
		blocks[name] = append(blocks[name], prof.Blocks...)
	}
	byPath := map[string]*emit.Result{}
	for _, gf := range gens {
		byPath[gf.path] = gf.g
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "mode: %s\n", profiles[0].Mode)
	for _, name := range names {
		bs := blocks[name]
		if g := byPath[name]; g != nil {
			bs = mapBlocks(g, bs)
		}
		for _, bl := range bs {
			fmt.Fprintf(&b, "%s:%d.%d,%d.%d %d %d\n", name, bl.StartLine, bl.StartCol, bl.EndLine, bl.EndCol, bl.NumStmt, bl.Count)
		}
	}
	return os.WriteFile(file, b.Bytes(), 0o644)
}

// lythBlock is a coverage block mapped to a byte range of a Lyth file.
type lythBlock struct {
	start, end int
	numStmt    int
	count      int
}

// mapBlocks maps the blocks of one generated file to its Lyth source. Each
// block becomes the range of the Lyth code that its outermost nodes came
// from. Blocks that land on the same range (the error check and the return
// that a postfix ? lowers to) are merged: the range counts as covered only if
// all of them ran, so an untested error path shows. Nested and overlapping
// ranges are then split so that every byte belongs to its innermost block,
// because cover profiles describe disjoint ranges.
func mapBlocks(g *emit.Result, blocks []cover.ProfileBlock) []cover.ProfileBlock {
	src := g.Map.Src
	lineStarts := []int{0}
	for i, c := range g.Code {
		if c == '\n' {
			lineStarts = append(lineStarts, i+1)
		}
	}
	offset := func(line, col int) int {
		if line < 1 || line > len(lineStarts) {
			return -1
		}
		return lineStarts[line-1] + col - 1
	}
	segs := g.Map.Segments // sorted by GenStart, longer first on ties
	merged := map[[2]int]*lythBlock{}
	for _, bl := range blocks {
		s, e := offset(bl.StartLine, bl.StartCol), offset(bl.EndLine, bl.EndCol)
		if s < 0 || e < s {
			continue
		}
		var span, synth source.Span
		outer := -1 // GenEnd of the last outermost segment taken
		for _, sg := range segs {
			if sg.GenStart >= e {
				break
			}
			if sg.GenStart < s || sg.GenEnd > e || sg.GenStart < outer || sg.Src.File != src {
				continue
			}
			outer = sg.GenEnd
			if sg.Synthetic {
				synth = synth.Join(sg.Src)
			} else {
				span = span.Join(sg.Src)
			}
		}
		if !span.IsValid() {
			span = synth
		}
		if !span.IsValid() {
			// No node lies inside the block: take the innermost one around it.
			for _, sg := range segs {
				if sg.GenStart <= s && s < sg.GenEnd && sg.Src.File == src {
					span = sg.Src
				}
			}
		}
		if !span.IsValid() || span.End <= span.Start {
			continue
		}
		key := [2]int{span.Start, span.End}
		if m := merged[key]; m != nil {
			m.count = min(m.count, bl.Count)
			m.numStmt = max(m.numStmt, bl.NumStmt)
		} else {
			merged[key] = &lythBlock{start: span.Start, end: span.End, numStmt: bl.NumStmt, count: bl.Count}
		}
	}
	var lb []*lythBlock
	for _, m := range merged {
		lb = append(lb, m)
	}
	// Paint larger blocks first so that inner ones win.
	sort.Slice(lb, func(i, j int) bool {
		if li, lj := lb[i].end-lb[i].start, lb[j].end-lb[j].start; li != lj {
			return li > lj
		}
		return lb[i].start < lb[j].start
	})
	owner := make([]int, len(src.Content))
	for i := range owner {
		owner[i] = -1
	}
	for i, m := range lb {
		for o := m.start; o < m.end && o < len(owner); o++ {
			owner[o] = i
		}
	}
	type run struct{ start, end, owner int }
	var runs []run
	for o := 0; o < len(owner); {
		if owner[o] < 0 {
			o++
			continue
		}
		r := run{start: o, owner: owner[o]}
		for o < len(owner) && owner[o] == r.owner {
			o++
		}
		r.end = o
		for r.start < r.end && isSpace(src.Content[r.start]) {
			r.start++
		}
		for r.end > r.start && isSpace(src.Content[r.end-1]) {
			r.end--
		}
		if r.start < r.end {
			runs = append(runs, r)
		}
	}
	// A block split into several runs keeps its statements in the first.
	stmts := make([]int, len(runs))
	placed := make([]bool, len(lb))
	for i, r := range runs {
		if !placed[r.owner] {
			stmts[i] = lb[r.owner].numStmt
			placed[r.owner] = true
		}
	}
	for i, m := range lb {
		if placed[i] {
			continue
		}
		// Hidden entirely by inner blocks: count its statements in the run
		// where it starts, or the next one.
		for j, r := range runs {
			if m.start < r.end {
				stmts[j] += m.numStmt
				break
			}
		}
	}
	pos := func(off int) (int, int) {
		line := src.Position(off).Line
		return line, off - src.LineStart(line) + 1
	}
	out := make([]cover.ProfileBlock, 0, len(runs))
	for i, r := range runs {
		sl, sc := pos(r.start)
		el, ec := pos(r.end)
		out = append(out, cover.ProfileBlock{StartLine: sl, StartCol: sc, EndLine: el, EndCol: ec, NumStmt: stmts[i], Count: lb[r.owner].count})
	}
	return out
}

func isSpace(c byte) bool { return c == ' ' || c == '\t' || c == '\n' || c == '\r' }

// CoverFunc prints the coverage of each function in a profile, like go tool
// cover -func, which cannot read profiles of Lyth code: it parses every file
// as Go. Lyth files are found in the module containing wd, other files
// through go list.
func CoverFunc(wd, profile string, w io.Writer, env []string) error {
	profiles, err := cover.ParseProfiles(profile)
	if err != nil {
		return err
	}
	dirs := map[string]string{} // import path -> directory
	if mod, err := FindModule(wd); err == nil {
		if pkgs, err := discover(mod); err == nil {
			for _, p := range pkgs {
				dirs[p.ImportPath] = p.Dir
			}
		}
	}
	var missing []string
	for _, prof := range profiles {
		if pkg := path.Dir(prof.FileName); !filepath.IsAbs(prof.FileName) && !strings.HasPrefix(prof.FileName, ".") && dirs[pkg] == "" && !slices.Contains(missing, pkg) {
			missing = append(missing, pkg)
		}
	}
	if len(missing) > 0 {
		cmd := exec.Command("go", append([]string{"list", "-e", "-json=ImportPath,Dir"}, missing...)...)
		cmd.Dir = wd
		cmd.Env = append(os.Environ(), env...)
		out, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("go list failed: %w", err)
		}
		dec := json.NewDecoder(bytes.NewReader(out))
		for dec.More() {
			var p struct{ ImportPath, Dir string }
			if err := dec.Decode(&p); err != nil {
				return err
			}
			dirs[p.ImportPath] = p.Dir
		}
	}
	tw := tabwriter.NewWriter(w, 1, 8, 1, '\t', 0)
	var covered, total int64
	for _, prof := range profiles {
		file := prof.FileName
		if !filepath.IsAbs(file) && !strings.HasPrefix(file, ".") {
			dir := dirs[path.Dir(file)]
			if dir == "" {
				return fmt.Errorf("did not find package for %s", file)
			}
			file = filepath.Join(dir, path.Base(file))
		}
		funcs, err := funcExtents(file)
		if err != nil {
			return err
		}
		for _, f := range funcs {
			c, t := f.coverage(prof)
			name := prof.FileName
			if filepath.IsAbs(name) {
				name = displayName(name, wd)
			}
			fmt.Fprintf(tw, "%s:%d:\t%s\t%.1f%%\n", name, f.startLine, f.name, percent(c, t))
			covered += c
			total += t
		}
	}
	fmt.Fprintf(tw, "total:\t(statements)\t%.1f%%\n", percent(covered, total))
	return tw.Flush()
}

// funcExtent is the extent of a function declaration, in byte columns.
type funcExtent struct {
	name                                 string
	startLine, startCol, endLine, endCol int
}

// funcExtents returns the function declarations of a Lyth or Go file.
func funcExtents(file string) ([]funcExtent, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	var out []funcExtent
	if strings.HasSuffix(file, ".lyth") {
		src := source.NewFile(file, file, data)
		sink := &diag.Sink{}
		f := syntax.Parse(src, sink)
		if sink.HasErrors() {
			return nil, fmt.Errorf("%s does not parse", file)
		}
		pos := func(off int) (int, int) {
			line := src.Position(off).Line
			return line, off - src.LineStart(line) + 1
		}
		for _, d := range f.Decls {
			if fd, ok := d.(*syntax.FunDecl); ok {
				sl, sc := pos(fd.S.Start)
				el, ec := pos(fd.S.End)
				out = append(out, funcExtent{fd.Name.Name, sl, sc, el, ec})
			}
		}
		return out, nil
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, data, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	for _, d := range f.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Body != nil {
			s, e := fset.Position(fd.Pos()), fset.Position(fd.End())
			out = append(out, funcExtent{fd.Name.Name, s.Line, s.Column, e.Line, e.Column})
		}
	}
	return out, nil
}

// coverage counts the statements of the blocks inside the function, as go
// tool cover -func does.
func (f funcExtent) coverage(p *cover.Profile) (covered, total int64) {
	for _, b := range p.Blocks {
		if b.StartLine > f.endLine || b.StartLine == f.endLine && b.StartCol >= f.endCol {
			break
		}
		if b.EndLine < f.startLine || b.EndLine == f.startLine && b.EndCol <= f.startCol {
			continue
		}
		total += int64(b.NumStmt)
		if b.Count > 0 {
			covered += int64(b.NumStmt)
		}
	}
	return covered, total
}

func percent(covered, total int64) float64 {
	if total == 0 {
		total = 1
	}
	return 100 * float64(covered) / float64(total)
}
