// stdModule is the module path of Lyth's standard library: a program imports
// its packages as lyth/<name>. The library is compiled from the sources in the
// lyth binary like the program's own packages, and the build finds it through
// a go.mod that requires and replaces the module (ADR 0030).
const stdModule = "lyth"

// stdPackage returns the standard-library package with import path path, or
// nil when path is not one. The library is written to the user cache on
// first use.
func (s *Session) stdPackage(path string) *pkgDir {
	rel, ok := strings.CutPrefix(path, stdModule+"/")
	if !ok || rel == "" {
		return nil
	}
	if info, err := fs.Stat(std.FS, rel); err != nil || !info.IsDir() {
		return nil
	}
	root, err := stdRoot()
	if err != nil {
		s.Sink.Errorf(diag.EImport, source.Span{}, "cannot prepare the Lyth standard library: %v", err)
		return nil
	}
	p, err := scanDir(&Module{Root: root, Path: stdModule}, filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil || p == nil {
		return nil
	}
	p.Rel = "_lythstd/" + rel // its place in .lyth/gen
	p.Std = true
	s.StdRoot = root
	return p
}

// stdRoot writes the embedded library to a directory of the user cache named
// after its content, unless it exists, and returns the directory.
func stdRoot() (string, error) {
	var files []string
	err := fs.WalkDir(std.FS, ".", func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			files = append(files, path)
		}
		return err
	})
	if err != nil {
		return "", err
	}
	h := sha256.New()
	for _, f := range files {
		data, _ := std.FS.ReadFile(f)
		fmt.Fprintf(h, "%s\x00%d\x00", f, len(data))
		h.Write(data)
	}
	cache, err := os.UserCacheDir()
	if err != nil {
		cache = os.TempDir()
	}
	root := filepath.Join(cache, "lyth", "std", hex.EncodeToString(h.Sum(nil))[:16])
	if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
		return canonical(root)
	}
	if err := os.MkdirAll(filepath.Dir(root), 0o755); err != nil {
		return "", err
	}
	// Write to a temporary directory and rename it, so a concurrent build
	// never sees a partial library.
	tmp, err := os.MkdirTemp(filepath.Dir(root), "tmp-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmp)
	for _, f := range files {
		data, _ := std.FS.ReadFile(f)
		path := filepath.Join(tmp, filepath.FromSlash(f))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return "", err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return "", err
		}
	}
	if err := os.WriteFile(filepath.Join(tmp, "go.mod"), []byte("module "+stdModule+"\n\ngo 1.26\n"), 0o644); err != nil {
		return "", err
	}
	if err := os.Rename(tmp, root); err != nil {
		if _, statErr := os.Stat(filepath.Join(root, "go.mod")); statErr != nil {
			return "", err
		}
	}
	return canonical(root)
}

// mentionsStd matches a go.mod line that requires or replaces the library.
var mentionsStd = regexp.MustCompile(`(?m)^\s*(require|replace)?\s*\(?\s*` + stdModule + `\s`)

// writeModFile writes .lyth/go.mod, the module's go.mod with the standard
// library required and replaced by its directory, for go commands to use
// through -modfile. The module's own go.mod stays as it is; one that already
// requires the library is used directly.
func (s *Session) writeModFile() error {
	data, err := os.ReadFile(filepath.Join(s.Mod.Root, "go.mod"))
	if err != nil {
		return err
	}
	if mentionsStd.Match(data) {
		return nil
	}
	if work := s.workspace(); work != "" {
		return s.writeWorkFile(work)
	}
	if s.vendorMode() {
		return fmt.Errorf("Lyth's standard library (%s/...) cannot be built from a vendor directory yet: the go command finds packages in vendor/modules.txt, which cannot list it\n\tbuild with GOFLAGS=-mod=mod to use the module cache, or do without %s/... in this module", stdModule, stdModule)
	}
	dir := filepath.Join(s.Mod.Root, ".lyth")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	content := strings.TrimRight(string(data), "\n") +
		"\n\nrequire " + stdModule + " v0.0.0\n\nreplace " + stdModule + " => " + strconv.Quote(s.StdRoot) + "\n"
	modFile := filepath.Join(dir, "go.mod")
	if err := writeIfChanged(modFile, []byte(content)); err != nil {
		return err
	}
	sum, err := os.ReadFile(filepath.Join(s.Mod.Root, "go.sum"))
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := writeIfChanged(filepath.Join(dir, "go.sum"), sum); err != nil {
		return err
	}
	_ = os.WriteFile(filepath.Join(dir, ".gitignore"), []byte("# Generated by lyth.\n*\n"), 0o644)
	s.ModFile = modFile
	return nil
}

// workspace returns the go.work that go commands in the module would use,
// or "": GOWORK when set (off disables it), else a go.work in the module's
// directory or above.
func (s *Session) workspace() string {
	gowork := os.Getenv("GOWORK")
	for _, kv := range s.cfg.Env {
		if v, ok := strings.CutPrefix(kv, "GOWORK="); ok {
			gowork = v
		}
	}
	switch gowork {
	case "off":
		return ""
	case "":
	default:
		return gowork
	}
	for dir := s.Mod.Root; ; dir = filepath.Dir(dir) {
		if _, err := os.Stat(filepath.Join(dir, "go.work")); err == nil {
			return filepath.Join(dir, "go.work")
		}
		if filepath.Dir(dir) == dir {
			return ""
		}
	}
}

// writeWorkFile writes .lyth/go.work: the workspace at work, its relative
// paths made absolute, with the standard library's module added, for go
// commands to use through GOWORK.
func (s *Session) writeWorkFile(work string) error {
	data, err := os.ReadFile(work)
	if err != nil {
		return err
	}
	wf, err := modfile.ParseWork(work, data, nil)
	if err != nil {
		return err
	}
	base := filepath.Dir(work)
	local := func(p string) string {
		if filepath.IsAbs(p) || !strings.HasPrefix(p, ".") {
			return p
		}
		return filepath.Join(base, p)
	}
	var b strings.Builder
	b.WriteString("// Generated by lyth from " + work + ".\n\n")
	if wf.Go != nil {
		b.WriteString("go " + wf.Go.Version + "\n")
	}
	if wf.Toolchain != nil {
		b.WriteString("toolchain " + wf.Toolchain.Name + "\n")
	}
	b.WriteString("\nuse (\n")
	for _, u := range wf.Use {
		b.WriteString("\t" + strconv.Quote(local(u.Path)) + "\n")
	}
	b.WriteString("\t" + strconv.Quote(s.StdRoot) + "\n)\n")
	for _, r := range wf.Replace {
		old := r.Old.Path
		if r.Old.Version != "" {
			old += " " + r.Old.Version
		}
		repl := strconv.Quote(local(r.New.Path))
		if r.New.Version != "" {
			repl = r.New.Path + " " + r.New.Version
		}
		b.WriteString("\nreplace " + old + " => " + repl + "\n")
	}
	dir := filepath.Join(s.Mod.Root, ".lyth")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	file := filepath.Join(dir, "go.work")
	if err := writeIfChanged(file, []byte(b.String())); err != nil {
		return err
	}
	sum, err := os.ReadFile(work + ".sum")
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if err := writeIfChanged(file+".sum", sum); err != nil {
		return err
	}
	_ = os.WriteFile(filepath.Join(dir, ".gitignore"), []byte("# Generated by lyth.\n*\n"), 0o644)
	s.WorkFile = file
	return nil
}

// vendorMode reports whether go commands in the module build from its vendor
// directory: vendor/modules.txt exists and GOFLAGS does not choose -mod=mod
// or -mod=readonly (Go 1.14 and later vendor by default then).
func (s *Session) vendorMode() bool {
	if _, err := os.Stat(filepath.Join(s.Mod.Root, "vendor", "modules.txt")); err != nil {
		return false
	}
	goflags := os.Getenv("GOFLAGS")
	for _, kv := range s.cfg.Env {
		if v, ok := strings.CutPrefix(kv, "GOFLAGS="); ok {
			goflags = v
		}
	}
	for _, f := range strings.Fields(goflags) {
		if f == "-mod=mod" || f == "-mod=readonly" {
			return false
		}
	}
	return true
}
