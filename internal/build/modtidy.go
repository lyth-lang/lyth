package build

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/lyth-lang/lyth/internal/diag"
	"github.com/lyth-lang/lyth/internal/source"
	"github.com/lyth-lang/lyth/internal/syntax"
)

// ModTidy runs `go mod tidy` so that dependencies imported only from .lyth
// files are kept and added. Plain `go mod tidy` cannot see them: generated
// Go lives in the overlay. Type checking is not required (tidy is how
// missing dependencies get added), so the overlay contains one stub per Lyth
// file with a blank import for each of the file's imports.
func ModTidy(cfg *Config, env []string) (*diag.Sink, error) {
	sink := &diag.Sink{}
	wd, err := canonical(cfg.WorkDir)
	if err != nil {
		return sink, err
	}
	mod, err := FindModule(wd)
	if err != nil {
		return sink, err
	}
	pkgs, err := discover(mod)
	if err != nil {
		return sink, err
	}
	stubDir := filepath.Join(mod.Root, ".lyth", "tidy")
	os.RemoveAll(stubDir)
	replace := map[string]string{}
	for _, p := range pkgs {
		var files []*syntax.File
		for _, path := range p.Files {
			data, err := os.ReadFile(path)
			if err != nil {
				return sink, err
			}
			files = append(files, syntax.Parse(source.NewFile(path, displayName(path, wd), data), sink))
		}
		name := stubPackageName(files, filepath.Base(p.Dir))
		for i, f := range files {
			var b strings.Builder
			fmt.Fprintf(&b, "// Code generated by lyth mod tidy. DO NOT EDIT.\n\npackage %s\n\n", name)
			var paths []string
			for _, imp := range f.Imports {
				// The standard library (lyth/coll) comes with the toolchain,
				// not from the module graph.
				if imp.Path != "" && !strings.HasPrefix(imp.Path, stdModule+"/") {
					paths = append(paths, imp.Path)
				}
			}
			sort.Strings(paths)
			for _, ip := range paths {
				fmt.Fprintf(&b, "import _ %s\n", strconv.Quote(ip))
			}
			genName := strings.TrimSuffix(filepath.Base(p.Files[i]), ".lyth")
			if strings.HasSuffix(genName, "_test") {
				genName = strings.TrimSuffix(genName, "_test") + ".lyth_test.go"
			} else {
				genName += ".lyth.go"
			}
			real := filepath.Join(stubDir, filepath.FromSlash(p.Rel), genName)
			if err := os.MkdirAll(filepath.Dir(real), 0o755); err != nil {
				return sink, err
			}
			if err := os.WriteFile(real, []byte(b.String()), 0o644); err != nil {
				return sink, err
			}
			replace[filepath.Join(p.Dir, genName)] = real
		}
	}
	data, _ := json.MarshalIndent(map[string]any{"Replace": replace}, "", "  ")
	overlay := filepath.Join(stubDir, "overlay.json")
	if err := os.WriteFile(overlay, data, 0o644); err != nil {
		return sink, err
	}
	cmd := exec.Command("go", "mod", "tidy", "-overlay="+overlay)
	cmd.Dir = mod.Root
	cmd.Env = append(append(os.Environ(), "PWD="+mod.Root), env...)
	cmd.Stdout, cmd.Stderr = cfg.Stdout, cfg.Stderr
	if err := cmd.Run(); err != nil {
		return sink, fmt.Errorf("go mod tidy failed: %w", err)
	}
	return sink, nil
}

// stubPackageName infers a package name without type checking.
func stubPackageName(files []*syntax.File, dir string) string {
	for _, f := range files {
		if f.Package != nil {
			return f.Package.Name
		}
	}
	for _, f := range files {
		for _, d := range f.Decls {
			if fd, ok := d.(*syntax.FunDecl); ok && fd.Recv == nil && fd.Name.Name == "main" {
				return "main"
			}
		}
	}
	return strings.ReplaceAll(dir, "-", "_")
}
